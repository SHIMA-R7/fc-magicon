"""Generate a rendering-disabled, FC-local two-nametable memory diagnostic."""
from pathlib import Path
import sys
sys.path.insert(0,str(Path(__file__).resolve().parents[1]/'tools'))
from asm6502 import Asm
cpu_window='--cpu-window' in sys.argv
settle_ppu='--settle-ppu' in sys.argv

PAT,PID,BANK,TARGET,REP,PAGE,SALT,SEQ,EXP,ACT,DIFF,ANY=range(0x10,0x1c)
R=0x20
READPASS,REQUEST=0x1c,0x1d
a=Asm(0xc000)
a.label('reset');a.sei();a.cld();a.ldx_imm(255);a.txs()
a.lda_imm(0);a.sta(0x2000);a.sta(0x2001);a.sta(0x4010)
for z in (PID,TARGET,REP,SEQ,ANY):a.sta_zp(z)
if cpu_window:a.sta_zp(REQUEST)
a.sta(0x5f20);a.lda_imm(0x40);a.sta(0x4017)
if settle_ppu:
    # >51k FC CPU clocks even if PPUSTATUS initially contains a stale VBlank flag.
    a.ldy_imm(40);a.label('settle_outer');a.ldx_imm(0)
    a.label('settle_inner');a.dex();a.bne('settle_inner');a.dey();a.bne('settle_outer')
    a.bit(0x2002)
for name in ('v1','v2'):
    a.label(name);a.bit(0x2002);a.bpl(name)
if settle_ppu:
    a.lda_imm(0);a.sta(0x2000);a.sta(0x2001);a.bit(0x2002)
a.label('round');a.ldx_imm(0);a.lda_imm(0)
a.label('clear');a.bytes_([0x95,R],'STA report,X');a.inx();a.cpx_imm(32);a.bne('clear')
a.lda_imm(255);a.sta_zp(R+6);a.sta_zp(R+7)
for source,dest in ((PID,R+1),(TARGET,R+2),(REP,R+3)):
    a.lda_zp(source);a.sta_zp(dest)
a.lda_imm(4);a.sta_zp(READPASS if cpu_window else R+28);a.lda_imm(0xc5 if cpu_window else 0xa5);a.sta_zp(R+30)
a.lda_zp(PID);a.tax();a.lda_absx('patterns');a.sta_zp(PAT)
if not cpu_window:a.sta_zp(R+11)
# Write distinct complementary values to both physical tables before checking either.
a.lda_imm(0);a.sta_zp(BANK);a.jsr('write_table')
a.lda_imm(1);a.sta_zp(BANK);a.jsr('write_table')
a.lda_zp(TARGET);a.sta_zp(BANK)
a.label('read_pass');a.jsr('address');a.lda_abs(0x2007)
a.lda_imm(0);a.sta_zp(PAGE);a.sta_zp(SALT);a.ldy_imm(0)
a.label('read_byte');a.jsr('expected');a.sta_zp(EXP)
a.lda_abs(0x2007);a.sta_zp(ACT);a.bytes_([0xc5,EXP],'CMP expected');a.beq('match')
a.jsr('mismatch')
a.label('match');a.iny();a.bne('read_byte')
a.inc_zp(PAGE);a.lda_zp(SALT);a.clc();a.adc_imm(0x41);a.sta_zp(SALT)
a.lda_zp(PAGE);a.cmp_imm(4);a.bne('read_byte')
a.dec_zp(READPASS if cpu_window else R+28);a.bne('read_pass')
a.inc_zp(SEQ);a.lda_zp(SEQ);a.sta_zp(R)
a.ldx_imm(0)
a.label('publish');a.bytes_([0xb5,R],'LDA report,X');a.sta_absx(0x5f80);a.inx();a.cpx_imm(32);a.bne('publish')
a.lda_zp(SEQ);a.sta(0x5f7e)
a.label('ack');a.lda_zp(SEQ);a.cmp_abs(0x5f7f);a.bne('ack')
a.inc_zp(PID);a.lda_zp(PID);a.cmp_imm(13);a.beq('next_bank');a.jmp('round')
a.label('next_bank');a.lda_imm(0);a.sta_zp(PID);a.inc_zp(TARGET)
a.lda_zp(TARGET);a.cmp_imm(2);a.beq('next_repeat');a.jmp('round')
a.label('next_repeat');a.lda_imm(0);a.sta_zp(TARGET);a.inc_zp(REP)
a.lda_zp(REP);a.cmp_imm(2);a.beq('finished');a.jmp('round')
a.label('finished');a.lda_zp(ANY);a.beq('pass');a.lda_imm(3);a.jmp('status')
a.label('pass');a.lda_imm(2)
a.label('status');a.sta(0x5f20)
a.cmp_imm(2);a.beq('green');a.lda_imm(0x16);a.jmp('colour')
a.label('green');a.lda_imm(0x1a)
a.label('colour');a.sta_zp(PAT);a.bit(0x2002)
a.lda_imm(0x3f);a.sta(0x2006);a.lda_imm(0);a.sta(0x2006);a.lda_zp(PAT);a.sta(0x2007)
a.lda_imm(0x20);a.sta(0x2006);a.lda_imm(0);a.sta(0x2006)
a.label('halt');a.jmp('halt')

a.label('address');a.bit(0x2002);a.lda_zp(BANK);a.beq('base0');a.lda_imm(0x2c);a.jmp('base')
a.label('base0');a.lda_imm(0x20)
a.label('base');a.sta_zp(R+29);a.sta(0x2006);a.lda_imm(0);a.sta(0x2006);a.rts()
a.label('expected');a.lda_zp(PID);a.cmp_imm(12);a.beq('address_value')
a.lda_zp(PAT);a.jmp('bank_tag')
a.label('address_value');a.tya();a.bytes_([0x45,SALT],'EOR page salt')
a.label('bank_tag');a.bytes_([0xa6,BANK],'LDX bank')
a.beq('expected_done');a.eor_imm(255)
a.label('expected_done');a.rts()
a.label('write_table')
if cpu_window:
    a.lda_zp(PID);a.sta(0x5f70);a.lda_zp(BANK);a.sta(0x5f71)
    a.inc_zp(REQUEST);a.lda_zp(REQUEST);a.sta(0x5f73)
    a.label('source_wait');a.lda_zp(REQUEST);a.cmp_abs(0x5f74);a.bne('source_wait')
    a.lda_imm(0);a.sta_zp(0x0c);a.lda_imm(0x60);a.sta_zp(0x0d)
a.jsr('address');a.lda_imm(0);a.sta_zp(PAGE);a.sta_zp(SALT);a.ldy_imm(0)
a.label('write_byte');a.jsr('expected')
if cpu_window:
    a.sta_zp(EXP);a.lda_indy(0x0c);a.sta_zp(ACT);a.bytes_([0xc5,EXP],'CMP local expected');a.beq('source_match')
    a.inc_zp(R+28);a.bne('source_counted');a.inc_zp(R+31)
    a.label('source_counted');a.lda_imm(1);a.sta_zp(ANY)
    a.lda_zp(ACT);a.bytes_([0x45,EXP],'EOR expected');a.ora_zp(R+11);a.sta_zp(R+11)
    a.label('source_match');a.lda_zp(ACT)
a.sta(0x2007);a.iny();a.bne('write_byte')
a.inc_zp(PAGE);a.lda_zp(SALT);a.clc();a.adc_imm(0x41);a.sta_zp(SALT)
if cpu_window:a.inc_zp(0x0d)
a.lda_zp(PAGE);a.cmp_imm(4);a.bne('write_byte');a.rts()

a.label('mismatch');a.lda_zp(R+4);a.ora_zp(R+5);a.bne('not_first')
a.tya();a.sta_zp(R+6);a.lda_zp(PAGE);a.sta_zp(R+7)
a.lda_zp(EXP);a.sta_zp(R+8);a.lda_zp(ACT);a.sta_zp(R+9)
a.label('not_first');a.inc_zp(R+4);a.bne('counted');a.inc_zp(R+5)
a.label('counted');a.lda_imm(1);a.sta_zp(ANY)
a.lda_zp(EXP);a.bytes_([0x45,ACT],'EOR actual');a.sta_zp(DIFF);a.ora_zp(R+10);a.sta_zp(R+10)
a.ldx_imm(0)
a.label('bit');a.lda_zp(DIFF);a.lsr_a();a.sta_zp(DIFF);a.bcc('next_bit')
a.bytes_([0xf6,R+12],'INC bit count low,X');a.bne('next_bit');a.bytes_([0xf6,R+13],'INC bit count high,X')
a.label('next_bit');a.inx();a.inx();a.cpx_imm(16);a.bne('bit');a.rts()
a.label('irq');a.rti()
a.label('patterns');a.bytes_([0,255,0x55,0xaa,1,2,4,8,16,32,64,128,0])
prg,listing=a.build(16384,{'nmi':'irq','reset':'reset','irq':'irq'})
out=Path(sys.argv[1]);out.write_text('#pragma once\n#include <stdint.h>\nstatic const uint8_t remote_prg[16384]={\n'+''.join(' '+','.join(f'0x{v:02x}' for v in prg[i:i+16])+',\n' for i in range(0,len(prg),16))+'};\nstatic const uint8_t remote_spr_chr[64]={0};\n',encoding='utf-8')
out.with_suffix('.bin').write_bytes(prg)
out.with_suffix('.lst').write_text('\n'.join(listing),encoding='utf-8')
print(('Generated CPU-window' if cpu_window else 'Generated FC-local')+' NT stress: 13 patterns x 2 banks x 2 repeats, four reads per write')

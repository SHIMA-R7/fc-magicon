"""Generate a tiny 6502 boot ROM. The waiting code executes in FC internal RAM."""
from pathlib import Path

ROOT = Path(__file__).resolve().parent

def generate():
    # $0200: acknowledge that the copy finished, poll, then use the game's vector.
    ram = bytes.fromhex('A9 A5 8D F1 FF AD F0 FF F0 FB 78 6C FC FF 40')
    code = bytearray.fromhex('78 D8 A2 FF 9A A9 00 8D 00 20 8D 01 20 8D 10 40 8D 15 40')
    code += bytes([0xA2, len(ram)-1])
    copy = len(code)
    source = 0x8000 + copy + 12
    code += bytes([0xBD, source & 255, source >> 8, 0x9D, 0, 2, 0xCA, 0x10, 0xF7, 0x4C, 0, 2])
    assert len(code) == source - 0x8000
    code += ram
    header = '// Generated by gen_boot.py; reset code at $8000.\n#pragma once\n'
    header += 'static const uint8_t fc_boot_code[] __attribute__((section(".data.fc_boot"))) = {' + ','.join(f'0x{x:02x}' for x in code) + '};\n'
    (ROOT/'boot_rom.h').write_text(header, encoding='utf-8')
    return bytes(code)

if __name__ == '__main__':
    print(f'Generated {len(generate())} bootstrap bytes')
